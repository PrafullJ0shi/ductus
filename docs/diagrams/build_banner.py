"""Build the README banner (light and dark) around a real ductus output line.

  python docs/diagrams/build_banner.py LINE.png
LINE.png is a crop of generated handwriting on white. Writes banner-light/dark .html (source)
and .png (2x) into docs/assets/. Rendered with headless Chrome."""
import base64, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASSETS = HERE.parent / "assets"
T = {
    "light": dict(paper="#FBFAF7", ink="#1D1F24", muted="#5C6170", rule="#D9D6CE", card="#FFFFFF"),
    "dark": dict(paper="#15171C", ink="#E8E6E1", muted="#A3A7B3", rule="#2C2F37", card="#FBFAF7"),
}
W, H = 1280, 360

PAGE = """<!doctype html><html><head><meta charset="utf-8"><title>ductus banner</title>
<style>
html,body{{margin:0;background:{paper};}}
.b{{width:{W}px;height:{H}px;box-sizing:border-box;padding:40px 56px;display:grid;
   grid-template-columns:400px 1fr;gap:40px;align-items:center;font-family:'Newsreader',serif;color:{ink}}}
h1{{font-size:72px;font-weight:500;margin:0;letter-spacing:-0.5px;line-height:1}}
p{{font-size:20px;line-height:28px;margin:16px 0 0;color:{ink}}}
.m{{font-family:'IBM Plex Mono',monospace;font-size:14px;color:{muted};margin-top:20px;line-height:20px}}
.card{{background:{card};border:1px solid {rule};border-radius:6px;padding:20px 24px;}}
.card img{{width:100%;display:block}}
.cap{{font-family:'IBM Plex Mono',monospace;font-size:12px;color:{muted};margin-top:8px}}
</style></head><body><div class="b">
<div><h1>ductus</h1>
<p>Text to handwriting: notes, maths and lists on A4, in a style copied from a photo.</p>
<div class="m">ductus write notes.txt --mode notes --photo</div></div>
<div><div class="card"><img alt="A line written by ductus" src="data:image/png;base64,{img}"></div>
<div class="cap">generated by ductus, natural look, blue ballpoint, unedited</div></div>
</div></body></html>"""


def main():
    img = base64.b64encode(Path(sys.argv[1]).read_bytes()).decode()
    for mode, t in T.items():
        html = ASSETS / f"banner-{mode}.html"
        html.write_text(PAGE.format(W=W, H=H, img=img, **t))
        png = ASSETS / f"banner-{mode}.png"
        subprocess.run(["google-chrome", "--headless=new", "--no-sandbox", "--hide-scrollbars",
                        "--force-device-scale-factor=2", f"--window-size={W},{H}",
                        f"--screenshot={png}", html.as_uri()], check=True, capture_output=True)
        print(png)


if __name__ == "__main__":
    main()
