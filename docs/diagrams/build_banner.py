"""Build the README banner (light and dark) around real ductus output.

  python docs/diagrams/build_banner.py OUTPUT.png INPUT.txt
OUTPUT.png: a crop of a page generated by ductus (unedited). INPUT.txt: the markup that
produced it. Writes docs/assets/banner-{light,dark}.html (source) and .png (2x, 1280x400 CSS
px), rendered with headless Chrome. Palette and type follow DESIGN.md."""
import base64, html, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASSETS = HERE.parent / "assets"
T = {
    "light": dict(bg="#FBFAF7", ink="#1D1F24", muted="#5C6170", rule="#D9D6CE", accent="#1C2A6E", code="#F2F0EA"),
    "dark": dict(bg="#15171C", ink="#E8E6E1", muted="#A3A7B3", rule="#33363F", accent="#8C9BE0", code="#1D2027"),
}
W, H = 1280, 400

PAGE = """<!doctype html><html lang="en"><head><meta charset="utf-8"><title>ductus</title>
<style>
html,body{{margin:0;background:{bg}}}
.b{{width:{W}px;height:{H}px;box-sizing:border-box;padding:30px 48px 26px;display:grid;
   grid-template-columns:284px 1fr;grid-template-rows:1fr auto;column-gap:40px;
   font-family:'Newsreader',serif;color:{ink}}}
.eyebrow{{font-family:'IBM Plex Mono',monospace;font-size:12px;letter-spacing:1.6px;color:{muted};text-transform:uppercase}}
h1{{font-size:84px;font-weight:500;margin:10px 0 0;line-height:1;letter-spacing:-1px}}
h1 span{{color:{accent}}}
.lede{{font-size:20px;line-height:28px;margin:16px 0 0;max-width:280px}}
.col{{display:flex;flex-direction:column;justify-content:center}}
.fig{{display:grid;grid-template-columns:300px 1fr;column-gap:32px;align-items:start;align-self:center}}
.lab{{font-family:'IBM Plex Mono',monospace;font-size:11px;letter-spacing:1.4px;color:{muted};text-transform:uppercase;margin-bottom:10px}}
pre{{margin:0;font-family:'IBM Plex Mono',monospace;font-size:12px;line-height:21px;color:{ink};
    background:{code};border:1px solid {rule};border-radius:4px;padding:14px 14px;white-space:pre;overflow:hidden}}
.paper{{background:#FFFFFF;border:1px solid {rule};border-radius:2px;padding:4px}}
.paper img{{width:100%;display:block}}
.foot{{grid-column:1 / span 2;border-top:1px solid {rule};padding-top:12px;display:flex;justify-content:space-between;
      font-family:'IBM Plex Mono',monospace;font-size:12px;color:{muted}}}
</style></head><body><div class="b">
<div class="col"><div class="eyebrow">Text to handwriting</div><h1>ductus<span>.</span></h1>
<p class="lede">Notes, maths and lists written by hand on A4, plain and readable.</p></div>
<div class="fig"><div><div class="lab">Input</div><pre>{src}</pre></div>
<div><div class="lab">Output, unedited</div><div class="paper"><img alt="Handwriting generated by ductus from the input" src="data:image/png;base64,{img}"></div></div></div>
<div class="foot"><span>ductus write notes.txt --mode notes</span><span>blue ballpoint, 300 dpi, A4</span></div>
</div></body></html>"""


def main():
    img = base64.b64encode(Path(sys.argv[1]).read_bytes()).decode()
    src = html.escape(Path(sys.argv[2]).read_text().strip())
    for mode, t in T.items():
        page = ASSETS / f"banner-{mode}.html"
        page.write_text(PAGE.format(W=W, H=H, img=img, src=src, **t))
        png = ASSETS / f"banner-{mode}.png"
        subprocess.run(["google-chrome", "--headless=new", "--no-sandbox", "--hide-scrollbars",
                        "--force-device-scale-factor=2", f"--window-size={W},{H}",
                        f"--screenshot={png}", page.as_uri()], check=True, capture_output=True)
        print(png)


if __name__ == "__main__":
    main()
